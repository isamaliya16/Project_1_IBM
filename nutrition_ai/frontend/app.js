// ── Tab Navigation ──────────────────────────────────────────────────────────
const navBtns = document.querySelectorAll('.nav-btn');
const tabSections = document.querySelectorAll('.tab-section');

navBtns.forEach(btn => {
  btn.addEventListener('click', () => {
    const target = btn.dataset.tab;
    navBtns.forEach(b => b.classList.remove('active'));
    btn.classList.add('active');
    tabSections.forEach(s => {
      s.classList.toggle('active', s.id === `tab-${target}`);
      s.classList.toggle('hidden', s.id !== `tab-${target}`);
    });
  });
});

// ── State ────────────────────────────────────────────────────────────────────
let currentUserProfile = {};
let currentMdFilename = '';

// ── Planner Form ─────────────────────────────────────────────────────────────
const plannerForm = document.getElementById('plannerForm');
const generateBtn = document.getElementById('generateBtn');
const planResult  = document.getElementById('planResult');
const planContent = document.getElementById('planContent');
const generationMeta = document.getElementById('generationMeta');
const loadingOverlay = document.getElementById('loadingOverlay');

plannerForm.addEventListener('submit', async (e) => {
  e.preventDefault();
  clearErrors();

  const formData = collectFormData();
  if (!validateForm(formData)) return;

  currentUserProfile = formData;
  showLoading(true);
  generateBtn.disabled = true;

  try {
    const response = await fetch('/api/generate-plan', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(formData)
    });

    const result = await response.json();

    if (result.success) {
      currentMdFilename = result.md_file || '';
      renderPlan(result.plan);
      generationMeta.textContent =
        `✅ Generated by IBM Granite AI | ${result.generated_at} | File: ${result.md_file || 'N/A'}`;
      planResult.classList.remove('hidden');
      planResult.scrollIntoView({ behavior: 'smooth', block: 'start' });
    } else {
      showFormError(result.error || 'Failed to generate plan. Please try again.');
    }
  } catch (err) {
    showFormError('Network error. Please ensure the server is running and try again.');
  } finally {
    showLoading(false);
    generateBtn.disabled = false;
  }
});

// ── Collect form data ────────────────────────────────────────────────────────
function collectFormData() {
  return {
    name:             document.getElementById('name').value.trim(),
    age:              document.getElementById('age').value.trim(),
    gender:           document.getElementById('gender').value,
    city:             document.getElementById('city').value.trim(),
    country:          document.getElementById('country').value.trim(),
    diet_preference:  document.getElementById('diet_preference').value,
    activity_level:   document.getElementById('activity_level').value,
    medical_history:  document.getElementById('medical_history').value.trim() || 'None',
    allergies:        document.getElementById('allergies').value.trim() || 'None',
    goals:            document.getElementById('goals').value.trim() || 'General healthy eating'
  };
}

// ── Client-side validation ────────────────────────────────────────────────────
function validateForm(data) {
  let valid = true;
  if (!data.name) { markError('name', 'Name is required'); valid = false; }
  if (!data.age || isNaN(data.age) || data.age < 1 || data.age > 120) {
    markError('age', 'Enter a valid age (1–120)'); valid = false;
  }
  if (!data.city) { markError('city', 'City is required'); valid = false; }
  if (!data.country) { markError('country', 'Country is required'); valid = false; }
  if (!data.diet_preference) { markError('diet_preference', 'Select a diet preference'); valid = false; }
  return valid;
}

function markError(fieldId, msg) {
  const el = document.getElementById(fieldId);
  if (el) {
    el.classList.add('error');
    const err = document.createElement('span');
    err.className = 'hint'; err.style.color = '#da1e28';
    err.textContent = msg;
    el.parentNode.appendChild(err);
  }
}

function clearErrors() {
  document.querySelectorAll('.error').forEach(el => el.classList.remove('error'));
  document.querySelectorAll('.hint[style]').forEach(el => el.remove());
  const existingErr = document.getElementById('formErrorMsg');
  if (existingErr) existingErr.remove();
}

function showFormError(msg) {
  let errDiv = document.getElementById('formErrorMsg');
  if (!errDiv) {
    errDiv = document.createElement('div');
    errDiv.id = 'formErrorMsg';
    errDiv.className = 'error-msg';
    generateBtn.parentNode.insertBefore(errDiv, generateBtn.nextSibling);
  }
  errDiv.textContent = '⚠️ ' + msg;
}

// ── Markdown renderer (lightweight, no library needed) ───────────────────────
function renderMarkdown(md) {
  let html = md
    // Headings
    .replace(/^### (.+)$/gm, '<h3>$1</h3>')
    .replace(/^## (.+)$/gm, '<h2>$1</h2>')
    .replace(/^# (.+)$/gm, '<h1>$1</h1>')
    // Bold & italic
    .replace(/\*\*\*(.+?)\*\*\*/g, '<strong><em>$1</em></strong>')
    .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
    .replace(/_(.+?)_/g, '<em>$1</em>')
    // Inline code
    .replace(/`([^`]+)`/g, '<code>$1</code>')
    // Blockquotes
    .replace(/^> (.+)$/gm, '<blockquote>$1</blockquote>')
    // HR
    .replace(/^---+$/gm, '<hr/>')
    // Tables
    .replace(/^\|(.+)\|$/gm, (match) => {
      const cols = match.slice(1, -1).split('|').map(c => c.trim());
      return '<tr>' + cols.map(c => `<td>${c}</td>`).join('') + '</tr>';
    })
    // Bullet lists
    .replace(/^\s*[-*] (.+)$/gm, '<li>$1</li>')
    // Ordered lists
    .replace(/^\d+\. (.+)$/gm, '<li>$1</li>')
    // Paragraphs
    .replace(/\n{2,}/g, '</p><p>')
    .replace(/\n/g, '<br/>');

  // Wrap consecutive <li> in <ul>
  html = html.replace(/(<li>.*?<\/li>)+/gs, (match) => `<ul>${match}</ul>`);
  // Wrap consecutive <tr> in <table>
  html = html.replace(/(<tr>.*?<\/tr>)+/gs, (match) => {
    const rows = match.match(/<tr>.*?<\/tr>/gs) || [];
    if (rows.length === 0) return match;
    const header = rows[0].replace(/<td>/g, '<th>').replace(/<\/td>/g, '</th>');
    const body = rows.slice(2).join('');  // skip separator row
    return `<table><thead>${header}</thead><tbody>${body}</tbody></table>`;
  });
  // Merge consecutive blockquotes
  html = html.replace(/<\/blockquote>\s*<blockquote>/g, '<br/>');

  return `<p>${html}</p>`;
}

function renderPlan(planText) {
  planContent.innerHTML = renderMarkdown(planText);
}

