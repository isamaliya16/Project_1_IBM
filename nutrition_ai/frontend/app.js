// ── Chat ──────────────────────────────────────────────────────────────────────
const chatMessages = document.getElementById('chatMessages');
const chatInput    = document.getElementById('chatInput');
const sendChatBtn  = document.getElementById('sendChatBtn');

async function sendChatMessage(message) {
  if (!message.trim()) return;

  appendChatMessage('user', message);
  chatInput.value = '';
  const typingId = appendTypingIndicator();

  try {
    const response = await fetch('/api/chat', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        message: message,
        user_profile: currentUserProfile
      })
    });
    const result = await response.json();
    removeTypingIndicator(typingId);

    if (result.success) {
      appendChatMessage('bot', result.reply);
    } else {
      appendChatMessage('bot', '⚠️ Sorry, I encountered an error. Please try again.');
    }
  } catch (err) {
    removeTypingIndicator(typingId);
    appendChatMessage('bot', '⚠️ Network error. Please check your connection and try again.');
  }
}

sendChatBtn.addEventListener('click', () => sendChatMessage(chatInput.value));
chatInput.addEventListener('keypress', (e) => {
  if (e.key === 'Enter' && !e.shiftKey) {
    e.preventDefault();
    sendChatMessage(chatInput.value);
  }
});

// Suggestion chips
document.querySelectorAll('.chip').forEach(chip => {
  chip.addEventListener('click', () => {
    document.querySelector('[data-tab="chat"]').click();
    sendChatMessage(chip.dataset.q);
  });
});

function appendChatMessage(role, text) {
  const msg = document.createElement('div');
  msg.className = `chat-message ${role === 'user' ? 'user-message' : 'bot-message'}`;
  msg.innerHTML = `
    <span class="msg-avatar">${role === 'user' ? '👤' : '🤖'}</span>
    <div class="msg-bubble">
      <strong>${role === 'user' ? 'You' : 'NutriGuide AI'}</strong>
      <p>${escapeHtml(text).replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>').replace(/\n/g, '<br/>')}</p>
    </div>`;
  chatMessages.appendChild(msg);
  chatMessages.scrollTop = chatMessages.scrollHeight;
}

function appendTypingIndicator() {
  const id = 'typing_' + Date.now();
  const msg = document.createElement('div');
  msg.id = id;
  msg.className = 'chat-message bot-message typing-indicator';
  msg.innerHTML = `
    <span class="msg-avatar">🤖</span>
    <div class="msg-bubble"><strong>NutriGuide AI</strong><p>Thinking...</p></div>`;
  chatMessages.appendChild(msg);
  chatMessages.scrollTop = chatMessages.scrollHeight;
  return id;
}

function removeTypingIndicator(id) {
  const el = document.getElementById(id);
  if (el) el.remove();
}

function escapeHtml(str) {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}
